class SE(nn.Module):
    def __init__(self, channel, ratio=3):  # ratio表示缩放比例
        super(SE, self).__init__()
        # c*1*1
        # 首先使用nn.AdaptiveAvgPool2d(1)将输入特征图进行自适应平均池化，将其尺寸调整为(batch_size, c1, 1, 1)
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.fc = nn.Sequential(
            # 线性全连接层，将输入通道数channel降低到channel // ratio。False表示不对全连接层的权重进行in-place操作。
            nn.Linear(channel, channel // ratio,False, ),
            # ReLU激活函数，用于增加非线性性
            nn.ReLU(inplace=False),
            # 线性全连接层，将通道数恢复到原始的channel大小。
            nn.Linear(channel // ratio, channel, False),
            # Sigmoid激活函数，将输出的通道权重限制在0到1之间
            nn.Sigmoid(),
        )

    def forward(self, x):
        b, c, h, w = x.size()  # 获取输入特征图的尺寸
        # 将输入特征图x通过self.avg-pool进行自适应平均池化，并使用view函数将结果的形状调整为(batch_size, c)，即将每个通道的特征图转换为一个向量
        y = self.avg_pool(x).view(b, c)
        y = self.fc(y).view(b, c, 1, 1)
        out = torch.mul(x, y.expand_as(x)).clone()  # 将结果赋值给out变量

        return out  # 返回out变量，而不是直接返回x

